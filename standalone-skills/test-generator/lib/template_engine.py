"""
template_engine.py — Jinja2-based generic SV template renderer.

Rewritten to be protocol-agnostic: templates iterate over spec data
(interfaces, signals, registers, fields) rather than being hardcoded
for specific protocols (GPIO, I2C, etc.).

Template variables use {{ var }} / {% for %} / {% if %} syntax (Jinja2).
"""

import os, sys, json, datetime
from typing import Dict, List, Optional, Any, Tuple
from jinja2 import Environment, FileSystemLoader, StrictUndefined

TEMPLATES_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "templates")

# Jinja2 environment with cache disabled for development
_jinja_env = Environment(
    loader=FileSystemLoader(TEMPLATES_DIR),
    undefined=StrictUndefined,
    trim_blocks=True,
    lstrip_blocks=True,
    autoescape=False,
)

# ── Filter: indent multi-line text ──
def _indent(text: Optional[str], width: int = 2) -> str:
    """Indent multi-line text by width spaces."""
    if not text:
        return ""
    lines = text.split("\n")
    return "\n".join(" " * width + l if l.strip() else "" for l in lines)


_jinja_env.filters["indent"] = _indent


def load_template(name: str) -> Optional[str]:
    """Load a template by name.  If name has an extension, use as-is;
    otherwise append .sv.tpl suffix. Returns None if not found."""
    base, ext = os.path.splitext(name)
    if ext:
        path = os.path.join(TEMPLATES_DIR, name)
    else:
        path = os.path.join(TEMPLATES_DIR, name + ".sv.tpl")
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            return f.read()
    return None


def render(template_name: str, data: Dict[str, Any]) -> Optional[str]:
    """Load and render a template with data dict using Jinja2. Returns None if template not found."""
    tpl = load_template(template_name)
    if tpl is None:
        return None
    try:
        template = _jinja_env.from_string(tpl)
        return template.render(**data)
    except Exception as e:
        print(f"  [TEMPLATE ERROR] {template_name}: {e}")
        print(f"  [FIX] Check template syntax in pipeline/templates/{template_name}")
        raise  # Re-raise so caller can detect failure


def render_to_file(template_name, data, out_path):
    """Render a template and write the result. Returns True on success."""
    try:
        content = render(template_name, data)
    except Exception:
        print(f"  [FAIL] Could not generate {os.path.basename(out_path)} — template error")
        return False
    if content is None:
        print(f"  [WARN] Template not found: {template_name}")
        return False
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by digital-verify-pro template engine\n")
        f.write(content)
    return True


